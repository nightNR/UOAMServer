using UOAMServer.Domain;
using UOAMServer.Protocol;

namespace UOAMServer.Server.Handlers;

public static class MysteryHandler
{
    // Copied verbatim from uoamhub.c's packet_response2.
    private static readonly byte[] Template =
    {
        0x05, 0x00, 0x0f, 0x03, 0x10, 0x00, 0x00, 0x00,
        0x38, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00,
        0xd0, 0x16, 0xd0, 0x16, 0xff, 0xff, 0xff, 0xff,
        0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x04, 0x5d, 0x88, 0x8a,
        0xeb, 0x1c, 0xc9, 0x11, 0x9f, 0xe8, 0x08, 0x00,
        0x2b, 0x10, 0x48, 0x60, 0x02, 0x00, 0x00, 0x00,
    };

    public static byte[] BuildResponse(Client client, uint sequence)
    {
        var response = (byte[])Template.Clone();
        ResponseHeader.WriteUInt32At(response, 20, client.Id);
        return ResponseHeader.Finalize(response, sequence);
    }
}
